using System.Text;

namespace PortingKit.Addons.Porting;

/// <summary>One driven helper. An <c>{s}</c> in a name expands to the side.</summary>
/// <param name="Fraction">Share of the control's roll the helper takes. Negative counters it.</param>
public sealed record TwistRule(string Helper, string Parent, string ControlParent, string Control, double Spread, double Fraction)
{
    /// <summary>This rule on one side of the body.</summary>
    public TwistRule Sided(string side) => this with
    {
        Helper = Helper.Replace("{s}", side, StringComparison.Ordinal), Parent = Parent.Replace("{s}", side, StringComparison.Ordinal),
        ControlParent = ControlParent.Replace("{s}", side, StringComparison.Ordinal), Control = Control.Replace("{s}", side, StringComparison.Ordinal)
    };
}

/// <summary>Generates the <c>$proceduralbones</c> file that drives a rig's twist helpers.</summary>
/// <remarks>
/// <para>A Source 2 character carries twist bones down the forearm, upper arm, thigh and neck. Renaming and keeping them is not
/// enough: on their own they hold bind and follow their parent rigidly, so the deformation they exist for never happens. An
/// elbow shears, a shoulder collapses, a wrist crimps. They have to be driven, and in Source that means a file read by
/// <c>$proceduralbones</c>.</para>
/// <para>The rules were read off a working port's hand-authored file. There are two families, and the difference is which way
/// the twist travels. Proximal helpers (Shoulder, Bicep, Hip, Quad) sit near the top of a limb and counter its roll, so a
/// deltoid stays put while the arm turns under it: full counter at the joint, half a little further down. Distal helpers
/// (Ulna, Wrist, Tibia, Soleus) sit near the far end and follow the roll of the joint past them, because a forearm's twist
/// comes from the wrist. The share rises the closer the helper sits to that joint.</para>
/// <para>Each block is <c>&lt;helper&gt; bone parent controlparent control</c>, then <c>&lt;basepos&gt; x y z</c>, then
/// <c>&lt;trigger&gt; tolerance ctrl-rx ry rz result-rx ry rz result-pos</c>. Euler triples are in SMD order, roll then pitch
/// then yaw, and the three triggers hold the control bone at its bind roll and at plus and minus the tolerance. That is what
/// makes the shares readable straight off a hand-authored file: 55 degrees of Ulna over 110 degrees of hand roll is one half,
/// not the 0.61 it looks like if you assume a 90 degree spread.</para>
/// </remarks>
public static class ProceduralBones
{
    /// <summary>Proximal helpers counter their limb; distal helpers follow the joint beyond them. Shares and spreads are taken
    /// from a working hand-authored rig.</summary>
    public static readonly IReadOnlyList<TwistRule> Rules =
    [
        new("Bip01_{s}_Shoulder", "Bip01_{s}_UpperArm", "Bip01_{s}_Clavicle", "Bip01_{s}_UpperArm", 90.0, -1.00),
        new("Bip01_{s}_Bicep", "Bip01_{s}_UpperArm", "Bip01_{s}_Clavicle", "Bip01_{s}_UpperArm", 90.0, -0.50),
        new("Bip01_{s}_Ulna", "Bip01_{s}_Forearm", "Bip01_{s}_Forearm", "Bip01_{s}_Hand", 110.0, 0.50),
        new("Bip01_{s}_Wrist", "Bip01_{s}_Forearm", "Bip01_{s}_Forearm", "Bip01_{s}_Hand", 110.0, 0.75),
        new("Bip01_{s}_Hip", "Bip01_{s}_Thigh", "Bip01_Pelvis", "Bip01_{s}_Thigh", 90.0, -1.00),
        new("Bip01_{s}_Quad", "Bip01_{s}_Thigh", "Bip01_Pelvis", "Bip01_{s}_Thigh", 90.0, -0.50),
        new("Bip01_{s}_Tibia", "Bip01_{s}_Calf", "Bip01_{s}_Calf", "Bip01_{s}_Foot", 90.0, 0.58),
        new("Bip01_{s}_Soleus", "Bip01_{s}_Calf", "Bip01_{s}_Calf", "Bip01_{s}_Foot", 90.0, 0.99)
    ];

    /// <summary>The neck twist has no side and follows the head at half rate.</summary>
    public static readonly TwistRule NeckRule = new("Bip01_Neck2", "Bip01_Neck1", "Bip01_Neck1", "Bip01_Head1", 90.0, 0.50);

    /// <summary>The text for every twist helper this rig actually has.</summary>
    /// <remarks>
    /// <para>Rules whose helper or control bone is missing are skipped in silence: a rig with no calf twists simply gets none,
    /// rather than a block naming a bone studiomdl would then refuse to resolve.</para>
    /// <para>The result of a trigger is the helper's absolute local rotation, not an offset, so the neutral trigger has to
    /// reproduce its own bind. Writing 0 0 0 there snaps every twist bone to identity at rest, which on an HLA rig is a 170
    /// degree jump, and the arm tears off sideways. A hand-authored rig gets away with 0 0 0 only because its helpers bind at
    /// identity. Twist is a roll about the helper's own X, and roll is the first term of Rz Ry Rx, so it simply adds there.</para>
    /// </remarks>
    public static string BuildVrd(GltfSkin skin, PortContext? context = null)
    {
        var index = Resolve(skin);
        var text = new StringBuilder();
        text.Append("// Generated by Source 2 Porting Kit - twist helper drivers.\n");
        text.Append("// Proximal helpers counter their limb's roll; distal helpers follow\n");
        text.Append("// the joint past them. Shares come from a hand-authored reference rig.\n");
        text.Append('\n');
        var rules = new[] { "L", "R" }.SelectMany(side => Rules.Select(rule => rule.Sided(side))).Append(NeckRule);
        var driven = 0;
        foreach (var rule in rules)
        {
            if (!index.TryGetValue(rule.Helper.ToLowerInvariant(), out var helper) || !index.TryGetValue(rule.Parent.ToLowerInvariant(), out var parent)
                || !index.TryGetValue(rule.Control.ToLowerInvariant(), out var control) || !index.TryGetValue(rule.ControlParent.ToLowerInvariant(), out var controlParent)) continue;
            var position = skin.Joints[helper].RestTranslation;
            var neutral = EulerXyz(M3.Of(M4.FromQuaternion(skin.Joints[control].RestRotation)));
            var bind = EulerXyz(M3.Of(M4.FromQuaternion(skin.Joints[helper].RestRotation)));
            var turn = rule.Fraction * rule.Spread;
            text.Append($"<helper>  {VrdName(skin.Joints[helper].Name)} {VrdName(skin.Joints[parent].Name)} {VrdName(skin.Joints[controlParent].Name)} {VrdName(skin.Joints[control].Name)}\n");
            text.Append($"<basepos> {Fmt.F6(position.X)} {Fmt.F6(position.Y)} {Fmt.F6(position.Z)}\n");
            foreach (var (offset, result) in new[] { (0.0, 0.0), (rule.Spread, turn), (-rule.Spread, -turn) })
                text.Append($"<trigger> {Fmt.G(rule.Spread)} {Fmt.F6(Wrap(neutral.X + offset))} {Fmt.F6(neutral.Y)} {Fmt.F6(neutral.Z)} {Fmt.F6(Wrap(bind.X + result))} {Fmt.F6(bind.Y)} {Fmt.F6(bind.Z)} 0 0 0\n");
            text.Append('\n');
            driven++;
        }
        if (driven > 0) context?.Log($"procedural bones: driving {driven} twist helper(s)");
        else context?.Warn("procedural bones: this rig has no twist helpers to drive");
        return text.ToString();
    }

    /// <summary>How studiomdl wants a bone written inside the file: without the namespace.</summary>
    /// <remarks>It matches <c>Bip01_L_Ulna</c>, not <c>ValveBiped.Bip01_L_Ulna</c>, and the failure is silent. The full name
    /// parses, compiles, and simply produces no procedural bone at all, and the only way to notice is to decode the finished
    /// model and find proctype zero on every bone.</remarks>
    private static string VrdName(string bone) => bone.StartsWith("ValveBiped.", StringComparison.Ordinal) ? bone["ValveBiped.".Length..] : bone;

    /// <summary>Bone stem to joint index, for canonical and <c>z_</c> helper names alike.</summary>
    /// <remarks>A helper may compile under the lowercase <c>z_</c> family, so <c>Bip01_L_Bicep</c> has to find
    /// <c>z_bip01_l_bicep</c> as readily as a canonical bone finds <c>ValveBiped.Bip01_L_Bicep</c>.</remarks>
    private static Dictionary<string, int> Resolve(GltfSkin skin)
    {
        var index = new Dictionary<string, int>(StringComparer.Ordinal);
        for (var joint = 0; joint < skin.Joints.Count; joint++)
        {
            var name = skin.Joints[joint].Name;
            if (name.StartsWith("ValveBiped.", StringComparison.Ordinal)) index.TryAdd(name["ValveBiped.".Length..].ToLowerInvariant(), joint);
            else if (name.StartsWith("z_", StringComparison.Ordinal)) index.TryAdd(name[2..].ToLowerInvariant(), joint);
            index.TryAdd(name.ToLowerInvariant(), joint);
        }
        return index;
    }

    /// <summary>Roll, pitch and yaw in degrees for Rz Ry Rx, the SMD convention.</summary>
    private static V3 EulerXyz(in M3 m)
    {
        var ry = Math.Asin(Math.Max(-1.0, Math.Min(1.0, -m.M20)));
        double rx, rz;
        if (Math.Abs(m.M20) < 0.9999999)
        {
            rx = Math.Atan2(m.M21, m.M22);
            rz = Math.Atan2(m.M10, m.M00);
        }
        else
        {
            rx = Math.Atan2(-m.M12, m.M11);
            rz = 0.0;
        }
        return new(Fmt.Degrees(rx), Fmt.Degrees(ry), Fmt.Degrees(rz));
    }

    /// <summary>Folds an angle into minus 180 exclusive to 180 inclusive, the range triggers are read in.</summary>
    private static double Wrap(double degrees)
    {
        var remainder = (degrees + 180.0) % 360.0;
        if (remainder < 0.0) remainder += 360.0;
        var value = remainder - 180.0;
        return value == -180.0 ? 180.0 : value;
    }
}
