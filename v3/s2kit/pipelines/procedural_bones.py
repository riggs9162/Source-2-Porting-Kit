"""Generate the `$proceduralbones` .vrd that drives a rig's twist helpers.

A Source 2 character carries twist bones down the forearm, upper arm, thigh and
neck. Renaming and keeping them is not enough: on their own they hold bind and
follow their parent rigidly, so the deformation they exist for never happens -
an elbow shears, a shoulder collapses, a wrist crimps. They have to be *driven*,
and in Source that means a `.vrd` read by `$proceduralbones`.

The rules here were read off a working port's hand-authored `grunt_helper.vrd`.
Two families, and the difference is which way the twist travels:

* **proximal** helpers - Shoulder, Bicep, Hip, Quad - sit near the top of a limb
  and **counter** its roll, so a shoulder deltoid stays put while the arm turns
  under it. Full counter at the joint, half a little further down.
* **distal** helpers - Ulna, Wrist, Tibia, Soleus - sit near the far end and
  **follow** the roll of the joint past them, because a forearm's twist comes
  from the wrist. The share rises the closer the helper sits to that joint.

File format, one block per helper::

    <helper>  <bone> <parent> <control parent> <control>
    <basepos> x y z
    <trigger> <tolerance> <ctrl rx ry rz> <result rx ry rz> <result pos x y z>

Bone names go in **without** the `ValveBiped.` namespace - studiomdl matches
`Bip01_L_Ulna` and silently ignores a block naming `ValveBiped.Bip01_L_Ulna`,
producing a model that compiles clean with no procedural bones in it at all.

Euler triples are in SMD order - ``(rx, ry, rz)``, roll then pitch then yaw -
and the three triggers hold the control bone at its bind roll and at plus and
minus the tolerance. That is what makes the shares readable straight off a
hand-authored file: 55 degrees of Ulna over 110 degrees of hand roll is one
half, not the 0.61 it looks like if you assume a 90-degree spread.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Dict, List, Optional, Sequence, Tuple

import numpy as np

from s2kit.pipelines.gltf_animation import GltfSkin
from s2kit.pipelines.porting import LogFn

__all__ = ["TwistRule", "RULES", "NECK_RULE", "build_vrd"]


@dataclass(frozen=True)
class TwistRule:
    """One driven helper. ``{s}`` expands to the L/R side."""
    helper: str
    parent: str
    control_parent: str
    control: str
    spread: float
    #: Share of the control's roll the helper takes. Negative counters it.
    fraction: float

    def sided(self, side: str) -> "TwistRule":
        return TwistRule(self.helper.format(s=side), self.parent.format(s=side),
                         self.control_parent.format(s=side),
                         self.control.format(s=side), self.spread, self.fraction)


#: Proximal helpers counter their limb; distal helpers follow the joint beyond
#: them. Shares and spreads are taken from a working hand-authored rig.
RULES: Sequence[TwistRule] = (
    TwistRule("Bip01_{s}_Shoulder", "Bip01_{s}_UpperArm", "Bip01_{s}_Clavicle",
              "Bip01_{s}_UpperArm", 90.0, -1.00),
    TwistRule("Bip01_{s}_Bicep", "Bip01_{s}_UpperArm", "Bip01_{s}_Clavicle",
              "Bip01_{s}_UpperArm", 90.0, -0.50),
    TwistRule("Bip01_{s}_Ulna", "Bip01_{s}_Forearm", "Bip01_{s}_Forearm",
              "Bip01_{s}_Hand", 110.0, 0.50),
    TwistRule("Bip01_{s}_Wrist", "Bip01_{s}_Forearm", "Bip01_{s}_Forearm",
              "Bip01_{s}_Hand", 110.0, 0.75),
    TwistRule("Bip01_{s}_Hip", "Bip01_{s}_Thigh", "Bip01_Pelvis",
              "Bip01_{s}_Thigh", 90.0, -1.00),
    TwistRule("Bip01_{s}_Quad", "Bip01_{s}_Thigh", "Bip01_Pelvis",
              "Bip01_{s}_Thigh", 90.0, -0.50),
    TwistRule("Bip01_{s}_Tibia", "Bip01_{s}_Calf", "Bip01_{s}_Calf",
              "Bip01_{s}_Foot", 90.0, 0.58),
    TwistRule("Bip01_{s}_Soleus", "Bip01_{s}_Calf", "Bip01_{s}_Calf",
              "Bip01_{s}_Foot", 90.0, 0.99),
)

#: The neck twist has no side and follows the head at half rate.
NECK_RULE = TwistRule("Bip01_Neck2", "Bip01_Neck1", "Bip01_Neck1",
                      "Bip01_Head1", 90.0, 0.50)


def build_vrd(skin: GltfSkin, *, on_log: Optional[LogFn] = None) -> str:
    """The .vrd text for every twist helper this rig actually has.

    Rules whose helper or control bone is missing are skipped in silence: a rig
    with no calf twists simply gets none, rather than a block naming a bone
    studiomdl would then refuse to resolve.
    """
    log = on_log or (lambda _m, _l="INFO": None)
    index = _resolve(skin)
    lines: List[str] = [
        "// Generated by Source 2 Porting Kit - twist helper drivers.",
        "// Proximal helpers counter their limb's roll; distal helpers follow",
        "// the joint past them. Shares come from a hand-authored reference rig.",
        "",
    ]
    rules = [rule.sided(side) for side in ("L", "R") for rule in RULES]
    rules.append(NECK_RULE)

    driven: List[str] = []
    for rule in rules:
        helper = index.get(rule.helper.lower())
        parent = index.get(rule.parent.lower())
        control = index.get(rule.control.lower())
        control_parent = index.get(rule.control_parent.lower())
        if helper is None or parent is None or control is None \
                or control_parent is None:
            continue

        base = skin.joints[helper].rest_translation
        neutral = _euler_xyz(_q2m(skin.joints[control].rest_rotation))
        # The result is the helper's ABSOLUTE local rotation, not an offset, so
        # the neutral trigger has to reproduce its own bind. Writing 0 0 0 there
        # snaps every twist bone to identity at rest - which on this rig is a
        # 170 degree jump, and the arm tears off sideways. A hand-authored rig
        # gets away with 0 0 0 only because its helpers bind at identity.
        bind = _euler_xyz(_q2m(skin.joints[helper].rest_rotation))
        turn = rule.fraction * rule.spread

        lines.append(f"<helper>  {_vrd_name(skin.joints[helper].name)} "
                     f"{_vrd_name(skin.joints[parent].name)} "
                     f"{_vrd_name(skin.joints[control_parent].name)} "
                     f"{_vrd_name(skin.joints[control].name)}")
        lines.append(f"<basepos> {base[0]:.6f} {base[1]:.6f} {base[2]:.6f}")
        for offset, result in ((0.0, 0.0), (rule.spread, turn),
                               (-rule.spread, -turn)):
            # Twist is a roll about the helper's own X, and roll is the first
            # term of R = Rz(yaw) Ry(pitch) Rx(roll), so it simply adds there.
            lines.append(
                f"<trigger> {rule.spread:g} "
                f"{_wrap(neutral[0] + offset):.6f} "
                f"{neutral[1]:.6f} {neutral[2]:.6f} "
                f"{_wrap(bind[0] + result):.6f} "
                f"{bind[1]:.6f} {bind[2]:.6f} 0 0 0")
        lines.append("")
        driven.append(skin.joints[helper].name)

    if driven:
        log(f"procedural bones: driving {len(driven)} twist helper(s)", "INFO")
    else:
        log("procedural bones: this rig has no twist helpers to drive",
            "WARNING")
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------------------

def _vrd_name(bone: str) -> str:
    """How studiomdl wants a bone written inside a .vrd: without the namespace.

    It matches `Bip01_L_Ulna`, not `ValveBiped.Bip01_L_Ulna`, and the failure
    is **silent** - the full name parses, compiles, and simply produces no
    procedural bone at all. The only way to notice is to decode the finished
    .mdl and find `proctype` zero on every bone, so the trimming happens here
    and a test asserts it.
    """
    return bone[len("ValveBiped."):] if bone.startswith("ValveBiped.") else bone


def _resolve(skin: GltfSkin) -> Dict[str, int]:
    """Bone stem -> joint index, for canonical and `z_` helper names alike.

    A helper compiles under the lowercase `z_` family, so `Bip01_L_Bicep` has to
    find `z_bip01_l_bicep` as readily as a canonical bone finds
    `ValveBiped.Bip01_L_Bicep`.
    """
    index: Dict[str, int] = {}
    for i, joint in enumerate(skin.joints):
        name = joint.name
        if name.startswith("ValveBiped."):
            index.setdefault(name[len("ValveBiped."):].lower(), i)
        elif name.startswith("z_"):
            index.setdefault(name[2:].lower(), i)
        index.setdefault(name.lower(), i)
    return index


def _euler_xyz(m: np.ndarray) -> Tuple[float, float, float]:
    """3x3 -> (rx, ry, rz) degrees for R = Rz @ Ry @ Rx, the SMD convention."""
    ry = np.arcsin(max(-1.0, min(1.0, -float(m[2, 0]))))
    if abs(float(m[2, 0])) < 0.9999999:
        rx = np.arctan2(float(m[2, 1]), float(m[2, 2]))
        rz = np.arctan2(float(m[1, 0]), float(m[0, 0]))
    else:
        rx = np.arctan2(-float(m[1, 2]), float(m[1, 1]))
        rz = 0.0
    return tuple(float(np.degrees(v)) for v in (rx, ry, rz))


def _wrap(degrees: float) -> float:
    """Fold an angle into (-180, 180], which is the range triggers are read in."""
    value = (float(degrees) + 180.0) % 360.0 - 180.0
    return 180.0 if value == -180.0 else value


def _q2m(q) -> np.ndarray:
    x, y, z, w = (float(v) for v in q)
    n = x * x + y * y + z * z + w * w
    if n < 1e-12:
        return np.eye(3)
    s = 2.0 / n
    xs, ys, zs = x * s, y * s, z * s
    return np.array([
        [1.0 - (y * ys + z * zs), x * ys - w * zs, x * zs + w * ys],
        [x * ys + w * zs, 1.0 - (x * xs + z * zs), y * zs - w * xs],
        [x * zs - w * ys, y * zs + w * xs, 1.0 - (x * xs + y * ys)],
    ], dtype=np.float64)
